CREATE TABLE organizations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL
);

CREATE TABLE membership (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    organization_id BIGINT NOT NULL,
    role VARCHAR(10) NOT NULL,
    CONSTRAINT membership_user_fk FOREIGN KEY (user_id) REFERENCES users(id),
    CONSTRAINT membership_organization_fk FOREIGN KEY (organization_id) REFERENCES organizations(id),
    CONSTRAINT uq_membership_user_organization UNIQUE (user_id, organization_id),
    CONSTRAINT role_ch CHECK ( role IN ('ADMIN', 'EDITOR', 'VIEWER') )
);

CREATE TABLE documents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(150) NOT NULL,
    content TEXT NOT NULL,
    organization_id BIGINT NOT NULL,
    created_by BIGINT NOT NULL,
    CONSTRAINT document_organization_fk FOREIGN KEY (organization_id) REFERENCES organizations(id),
    CONSTRAINT document_user_fk FOREIGN KEY (created_by) REFERENCES  users(id)
);